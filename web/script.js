function setLanguage(language) {
    const selectedLanguage = translations[language] ? language : "sr";
    const dictionary = translations[selectedLanguage];

    document.documentElement.lang = selectedLanguage;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.dataset.i18n;

        if (Object.hasOwn(dictionary, key)) {
            element.innerHTML = dictionary[key];
        }
    });

    document.querySelectorAll("[data-language]").forEach((button) => {
        const isActive = button.dataset.language === selectedLanguage;

        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });

    document.title = dictionary.pageTitle;

    const description = document.querySelector('meta[name="description"]');
    if (description) {
        description.setAttribute("content", dictionary.pageDescription);
    }

    try {
        localStorage.setItem("portfolio-language", selectedLanguage);
    } catch (error) {
        // Jezik će raditi i ako pregledač ne dozvoljava localStorage.
    }
}

document.querySelectorAll("[data-language]").forEach((button) => {
    button.addEventListener("click", () => {
        setLanguage(button.dataset.language);
    });
});

document.getElementById("year").textContent = new Date().getFullYear();

